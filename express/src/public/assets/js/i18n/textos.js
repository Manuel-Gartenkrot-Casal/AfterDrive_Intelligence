/* "en cola (#2)" dentro de una frase. */
function _enCola(x, cod) {
  var m = /en cola \(#(\d+)\)/.exec(x);
  if (!m) return x;
  return cod === 'pt' ? 'na fila (#' + m[1] + ')' : 'queued (#' + m[1] + ')';
}
